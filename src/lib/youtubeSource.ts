/**
 * Step 5: yt-dlp audio + openai-whisper.
 * When caption endpoints return 429, audio stream often still downloads.
 */
async function fetchTranscriptViaAudioWhisper(
  videoId: string,
  preferredLangs: string[],
): Promise<AudioWhisperOk | AudioWhisperFail> {
  const script = resolveAudioTranscriptScript();
  if (!script) {
    return {
      ok: false,
      code: 'SCRIPT_MISSING',
      detail: 'Thiếu fetch_youtube_audio_transcript.py trong pack.',
    };
  }
  const lang =
    preferredLangs.map((l) => l.split('-')[0].toLowerCase()).find(Boolean) || 'auto';
  const model = (process.env.AINOVEL_YT_WHISPER_MODEL || 'tiny').trim() || 'tiny';
  let lastDetail = '';
  let lastCode: YoutubeTranscriptFailCode | undefined;

  for (const bin of pythonBins()) {
    const result = await new Promise<AudioWhisperOk | AudioWhisperFail>((resolve) => {
      let settled = false;
      const finish = (v: AudioWhisperOk | AudioWhisperFail) => {
        if (settled) return;
        settled = true;
        resolve(v);
      };
      let child;
      try {
        child = spawn(bin, [script, videoId, lang, model], {
          windowsHide: true,
          shell: false,
          env: {
            ...process.env,
            PYTHONIOENCODING: 'utf-8',
            PYTHONUTF8: '1',
          },
        });
      } catch (e) {
        finish({
          ok: false,
          code: 'PYTHON_NOT_FOUND',
          detail: e instanceof Error ? e.message : String(e),
        });
        return;
      }
      const chunks: Buffer[] = [];
      const errChunks: Buffer[] = [];
      // Long videos: download + whisper tiny can take several minutes
      const timer = setTimeout(() => {
        try {
          child.kill();
        } catch {
          /* ignore */
        }
        finish({
          ok: false,
          code: 'TIMEOUT',
          detail: `Timeout 600s audio+whisper với «${bin}».`,
        });
      }, 600_000);

      child.stdout?.on('data', (d: Buffer | string) => {
        chunks.push(Buffer.isBuffer(d) ? d : Buffer.from(String(d)));
      });
      child.stderr?.on('data', (d: Buffer | string) => {
        errChunks.push(Buffer.isBuffer(d) ? d : Buffer.from(String(d)));
      });
      child.on('error', (err) => {
        clearTimeout(timer);
        finish({
          ok: false,
          code: 'PYTHON_NOT_FOUND',
          detail: `${bin}: ${err.message}`,
        });
      });
      child.on('close', () => {
        clearTimeout(timer);
        try {
          const out = Buffer.concat(chunks).toString('utf8');
          const line = out.trim().split(/\r?\n/).filter(Boolean).pop() || '';
          if (!line) {
            const stderr = Buffer.concat(errChunks).toString('utf8').trim().slice(0, 300);
            finish({
              ok: false,
              code: 'FETCH_FAILED',
              detail: stderr || `Python «${bin}» audio-whisper không trả JSON.`,
            });
            return;
          }
          const j = JSON.parse(line) as {
            ok?: boolean;
            transcript?: string;
            language?: string;
            title?: string;
            error?: string;
            code?: string;
          };
          if (j.ok && j.transcript && j.transcript.trim().length >= 10) {
            finish({
              ok: true,
              transcript: j.transcript.trim(),
              language: j.language,
              title: j.title,
            });
            return;
          }
          const code =
            normalizePyCode(j.code) ||
            (String(j.error || '').includes('not installed')
              ? 'PACKAGE_MISSING'
              : 'FETCH_FAILED');
          finish({
            ok: false,
            code,
            detail: String(j.error || 'audio whisper failed').slice(0, 400),
          });
        } catch (e) {
          finish({
            ok: false,
            code: 'FETCH_FAILED',
            detail: e instanceof Error ? e.message : String(e),
          });
        }
      });
    });

    if (result.ok) return result;
    lastDetail = result.detail;
    lastCode = result.code;
    // PACKAGE_MISSING on one python — try next bin (system may have whisper)
    if (
      result.code === 'VIDEO_UNAVAILABLE' ||
      result.code === 'AGE_RESTRICTED' ||
      result.code === 'EMPTY_TRANSCRIPT'
    ) {
      return result;
    }
  }

  return {
    ok: false,
    code: lastCode || 'FETCH_FAILED',
    detail: lastDetail || 'audio+whisper failed',
  };
}

/**
 * Python candidates for youtube-transcript-api.
 * Order: PATH `python`/`py` first (user often `pip install` here), then
 * resolvePythonExe (portable / SuperAudioTools — may lack youtube-transcript-api).
 * Ver 1.0.5 bug: only bare PATH names; then preferred Omni python without package
 * wasted first attempt. Timedtext still runs if all Python fail.
 */
function pythonBins(): string[] {
  const bins: string[] = [];
  if (process.platform === 'win32') {
    bins.push('python', 'py', 'python3');
  } else {
    bins.push('python3', 'python');
  }
  try {
    const preferred = resolvePythonExe();
    // Avoid pushing bare "python" twice; absolute paths always append
    if (preferred && preferred !== 'python' && preferred !== 'py' && preferred !== 'python3') {
      bins.push(preferred);
    }
  } catch {
    /* ignore */
  }
  return [...new Set(bins.map((b) => b.trim()).filter(Boolean))];
}

/**
 * Timedtext / player caption track — same content type as captions (NOT description).
 * Used only after Python path fails so white machines / missing pip package still work.
 */
async function fetchTranscriptViaTimedtext(
  tracks: CaptionTrack[],
  preferredLangs: string[],
): Promise<{
  ok: true;
  transcript: string;
  language?: string;
  isAutoGenerated?: boolean;
} | { ok: false; detail: string }> {
  if (!tracks.length) {
    return { ok: false, detail: 'Player không có captionTracks.' };
  }
  const track = pickCaptionTrack(tracks, preferredLangs);
  if (!track?.baseUrl) {
    return { ok: false, detail: 'Không chọn được caption track phù hợp.' };
  }
  try {
    // Prefer json3 then srv3/xml
    const base = track.baseUrl;
    const urls = [
      base.includes('fmt=') ? base : `${base}${base.includes('?') ? '&' : '?'}fmt=json3`,
      base,
    ];
    let lastDetail = '';
    for (const u of urls) {
      try {
        const res = await fetch(u, {
          headers: {
            'User-Agent':
              'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36',
            Accept: 'application/json, text/xml, */*',
            Referer: 'https://www.youtube.com/',
            'Accept-Language': 'vi-VN,vi;q=0.9,en-US;q=0.8,en;q=0.7',
          },
        });
        const body = await res.text();
        if (res.status === 429 || /Sorry\.\.\.|too many requests|rate.?limit/i.test(body)) {
          return {
            ok: false,
            detail: `Timedtext HTTP ${res.status} (YouTube rate-limit / chặn IP).`,
          };
        }
        if (!res.ok) {
          lastDetail = `Timedtext HTTP ${res.status}`;
          continue;
        }
        let text = '';
        if (body.trimStart().startsWith('{') || body.includes('"events"')) {
          text = parseCaptionJson3(body);
        } else {
          text = parseCaptionXml(body);
        }
        if (text.length >= 20) {
          return {
            ok: true,
            transcript: text,
            language: track.languageCode,
            isAutoGenerated:
              track.kind === 'asr' || String(track.vssId || '').includes('.a'),
          };
        }
        lastDetail = `Track ${track.languageCode || '?'} quá ngắn (${text.length} ký tự).`;
      } catch (e) {
        lastDetail = e instanceof Error ? e.message : String(e);
      }
    }
    return { ok: false, detail: lastDetail || 'timedtext empty' };
  } catch (e) {
    return {
      ok: false,
      detail: e instanceof Error ? e.message : String(e),
    };
  }
}

type PythonTranscriptOk = {
  ok: true;
  transcript: string;
  language?: string;
  isAutoGenerated?: boolean;
};

type PythonTranscriptFail = {
  ok: false;
  code: YoutubeTranscriptFailCode;
  detail: string;
  triedBins: string[];
};

type PythonTranscriptResult = PythonTranscriptOk | PythonTranscriptFail;

function normalizePyCode(raw: string | undefined): YoutubeTranscriptFailCode | null {
  if (!raw) return null;
  const c = raw.trim().toUpperCase();
  const known: YoutubeTranscriptFailCode[] = [
    'INVALID_URL',
    'SCRIPT_MISSING',
    'PYTHON_NOT_FOUND',
    'PACKAGE_MISSING',
    'TIMEOUT',
    'NO_TRANSCRIPT',
    'TRANSCRIPTS_DISABLED',
    'VIDEO_UNAVAILABLE',
    'AGE_RESTRICTED',
    'IP_BLOCKED',
    'RATE_LIMITED',
    'EMPTY_TRANSCRIPT',
    'FETCH_FAILED',
    'NETWORK',
  ];
  return (known as string[]).includes(c) ? (c as YoutubeTranscriptFailCode) : null;
}

