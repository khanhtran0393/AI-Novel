function watchUrl(videoId: string): string {
  return `https://www.youtube.com/watch?v=${videoId}`;
}

function decodeHtmlEntities(text: string): string {
  return text
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&#x27;/g, "'")
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)))
    .replace(/&#x([0-9a-fA-F]+);/g, (_, h) => String.fromCharCode(parseInt(h, 16)));
}

function truncate(s: string, max: number): string {
  const t = s.trim();
  if (t.length <= max) return t;
  return `${t.slice(0, max - 1).trimEnd()}…`;
}

function parsePlayerResponse(html: string): Record<string, unknown> | null {
  const markers = [
    /ytInitialPlayerResponse\s*=\s*(\{)/,
    /var\s+ytInitialPlayerResponse\s*=\s*(\{)/,
  ];
  for (const re of markers) {
    const m = html.match(re);
    if (!m || m.index == null) continue;
    const start = m.index + m[0].length - 1;
    const json = extractBalancedJson(html, start);
    if (json) {
      try {
        return JSON.parse(json) as Record<string, unknown>;
      } catch {
        /* try next */
      }
    }
  }
  return null;
}

/** Extract JSON object starting at `{` by brace balance (string-aware). */
function extractBalancedJson(src: string, startIdx: number): string | null {
  if (src[startIdx] !== '{') return null;
  let depth = 0;
  let inStr = false;
  let esc = false;
  for (let i = startIdx; i < src.length; i++) {
    const c = src[i];
    if (inStr) {
      if (esc) {
        esc = false;
      } else if (c === '\\') {
        esc = true;
      } else if (c === '"') {
        inStr = false;
      }
      continue;
    }
    if (c === '"') {
      inStr = true;
      continue;
    }
    if (c === '{') depth++;
    else if (c === '}') {
      depth--;
      if (depth === 0) return src.slice(startIdx, i + 1);
    }
  }
  return null;
}

type CaptionTrack = {
  baseUrl: string;
  languageCode?: string;
  name?: string;
  kind?: string;
  vssId?: string;
};

function pickCaptionTrack(
  tracks: CaptionTrack[],
  preferredLangs: string[],
): CaptionTrack | null {
  if (!tracks.length) return null;
  const norm = preferredLangs.map((l) => l.toLowerCase().split('-')[0]);

  const score = (t: CaptionTrack): number => {
    const code = (t.languageCode || '').toLowerCase();
    const base = code.split('-')[0];
    let s = 0;
    const prefIdx = norm.indexOf(base);
    if (prefIdx >= 0) s += 100 - prefIdx * 10;
    // Prefer manual over ASR
    if (t.kind !== 'asr' && !String(t.vssId || '').includes('.a')) s += 20;
    if (base === 'vi') s += 5;
    if (base === 'en') s += 3;
    return s;
  };

  return [...tracks].sort((a, b) => score(b) - score(a))[0] || null;
}

function parseCaptionXml(xml: string): string {
  const parts: string[] = [];
  const re = /<text\b[^>]*>([\s\S]*?)<\/text>/gi;
  let m: RegExpExecArray | null;
  while ((m = re.exec(xml)) !== null) {
    const raw = m[1]
      .replace(/<[^>]+>/g, ' ')
      .replace(/\n+/g, ' ')
      .trim();
    const text = decodeHtmlEntities(raw).replace(/\s+/g, ' ').trim();
    if (text) parts.push(text);
  }
  return parts.join(' ').replace(/\s+/g, ' ').trim();
}

function parseCaptionJson3(jsonText: string): string {
  try {
    const data = JSON.parse(jsonText) as {
      events?: Array<{ segs?: Array<{ utf8?: string }> }>;
    };
    const parts: string[] = [];
    for (const ev of data.events || []) {
      for (const seg of ev.segs || []) {
        const t = (seg.utf8 || '').replace(/\n/g, ' ').trim();
        if (t && t !== '\n') parts.push(t);
      }
    }
    return parts.join(' ').replace(/\s+/g, ' ').trim();
  } catch {
    return '';
  }
}

/** WEBVTT / SRT-ish → plain dialogue (dedupe consecutive auto-caption lines). */
export function parseSubtitleFileToText(raw: string): string {
  const text = (raw || '').replace(/^\uFEFF/, '');
  if (!text.trim()) return '';
  // json3 dumped as file
  if (text.trimStart().startsWith('{') && text.includes('"events"')) {
    return parseCaptionJson3(text);
  }
  const parts: string[] = [];
  let prev = '';
  for (const line of text.split(/\r?\n/)) {
    const t = line.trim();
    if (!t) continue;
    if (
      /^WEBVTT/i.test(t) ||
      /^NOTE\b/i.test(t) ||
      /^Kind:/i.test(t) ||
      /^Language:/i.test(t) ||
      /^STYLE\b/i.test(t) ||
      /^REGION\b/i.test(t) ||
      t.includes('-->') ||
      /^\d+$/.test(t) ||
      /^[\d:.,\s→>-]+$/.test(t)
    ) {
      continue;
    }
    const clean = decodeHtmlEntities(t.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim());
    if (!clean || clean === prev) continue;
    parts.push(clean);
    prev = clean;
  }
  return parts.join(' ').replace(/\s+/g, ' ').trim();
}

type YtdlpOk = {
  ok: true;
  transcript: string;
  language?: string;
  isAutoGenerated?: boolean;
};

type YtdlpFail = {
  ok: false;
  detail: string;
  rateLimited?: boolean;
};

/**
 * Resolve yt-dlp invocations: bare `yt-dlp` then `python -m yt_dlp` for each python bin.
 */
function ytdlpInvocations(): string[][] {
  const inv: string[][] = [['yt-dlp']];
  for (const bin of pythonBins()) {
    inv.push([bin, '-m', 'yt_dlp']);
  }
  return inv;
}

function pickBestSubtitleFile(
  dir: string,
  preferredLangs: string[],
): { file: string; language?: string; isAuto: boolean } | null {
  let files: string[] = [];
  try {
    files = fs
      .readdirSync(dir)
      .filter((f) => /\.(vtt|srt|ttml|srv3|json3)$/i.test(f));
  } catch {
    return null;
  }
  if (!files.length) return null;

  const pref = preferredLangs.map((l) => l.toLowerCase().split('-')[0]);
  const score = (name: string): number => {
    const low = name.toLowerCase();
    let s = 0;
    // lang token after videoId: id.en.vtt / id.en-en.vtt / id.vi-en.vtt
    const m = low.match(/\.([a-z]{2,3})(?:-[a-z0-9]+)*\.(vtt|srt|ttml|srv3|json3)$/i);
    const lang = m?.[1] || '';
    const prefIdx = pref.indexOf(lang);
    if (prefIdx >= 0) s += 100 - prefIdx * 10;
    if (lang === 'vi') s += 5;
    if (lang === 'en') s += 3;
    if (low.endsWith('.vtt')) s += 2;
    // manual subs often lack "auto" in name; auto-subs sometimes tagged
    if (/auto/i.test(low)) s -= 1;
    return s;
  };

  const sorted = [...files].sort((a, b) => score(b) - score(a));
  const best = sorted[0];
  const langM = best.match(/\.([a-z]{2,3})(?:-[a-z0-9]+)*\.(vtt|srt|ttml|srv3|json3)$/i);
  return {
    file: path.join(dir, best),
    language: langM?.[1],
    isAuto: /auto|from-/i.test(best),
  };
}

/**
 * Step 4: yt-dlp subs only (no video download).
 * Different client stack than timedtext/python-api — often survives when those 429.
 */
async function fetchTranscriptViaYtdlp(
  videoId: string,
  preferredLangs: string[],
): Promise<YtdlpOk | YtdlpFail> {
  const url = watchUrl(videoId);
  const bases = preferredLangs
    .map((l) => l.split('-')[0].toLowerCase())
    .filter(Boolean);
  // CẤM "en.*" (hàng trăm auto-translate) — spam 429. Chỉ vài lang gốc.
  const uniqLangs = [...new Set([...bases, 'en', 'vi'])].slice(0, 4);
  const subLangs = uniqLangs.join(',');

  const tmpRoot = path.join(os.tmpdir(), 'ainovel-yt-subs');
  let tmpDir = '';
  try {
    fs.mkdirSync(tmpRoot, { recursive: true });
    tmpDir = fs.mkdtempSync(path.join(tmpRoot, `${videoId}-`));
  } catch (e) {
    return {
      ok: false,
      detail: `Không tạo temp yt-dlp: ${e instanceof Error ? e.message : String(e)}`,
    };
  }

  const outTpl = path.join(tmpDir, videoId);
  const argsCommon = [
    '--skip-download',
    '--write-subs',
    '--write-auto-subs',
    '--sub-langs',
    subLangs,
    '--sub-format',
    'vtt/best',
    '--no-playlist',
    '--no-warnings',
    '--ignore-errors',
    '-o',
    outTpl,
    '--',
    url,
  ];

  let lastDetail = '';
  let rateLimited = false;
  let anySpawned = false;

  try {
    for (const inv of ytdlpInvocations()) {
      const bin = inv[0];
      const prefix = inv.slice(1);
      const args = [...prefix, ...argsCommon];
      const result = await new Promise<{
        code: number | null;
        stdout: string;
        stderr: string;
        spawnError?: string;
      }>((resolve) => {
        let settled = false;
        const finish = (v: {
          code: number | null;
          stdout: string;
          stderr: string;
          spawnError?: string;
        }) => {
          if (settled) return;
          settled = true;
          resolve(v);
        };
        let child;
        try {
          child = spawn(bin, args, {
            windowsHide: true,
            shell: false,
            env: {
              ...process.env,
              PYTHONIOENCODING: 'utf-8',
              PYTHONUTF8: '1',
            },
          });
          anySpawned = true;
        } catch (e) {
          finish({
            code: null,
            stdout: '',
            stderr: '',
            spawnError: e instanceof Error ? e.message : String(e),
          });
          return;
        }
        const outChunks: Buffer[] = [];
        const errChunks: Buffer[] = [];
        const timer = setTimeout(() => {
          try {
            child.kill();
          } catch {
            /* ignore */
          }
          finish({
            code: null,
            stdout: Buffer.concat(outChunks).toString('utf8'),
            stderr: Buffer.concat(errChunks).toString('utf8') + '\nTIMEOUT 90s',
          });
        }, 90_000);
        child.stdout?.on('data', (d: Buffer | string) => {
          outChunks.push(Buffer.isBuffer(d) ? d : Buffer.from(String(d)));
        });
        child.stderr?.on('data', (d: Buffer | string) => {
          errChunks.push(Buffer.isBuffer(d) ? d : Buffer.from(String(d)));
        });
        child.on('error', (err) => {
          clearTimeout(timer);
          finish({
            code: null,
            stdout: '',
            stderr: '',
            spawnError: `${bin}: ${err.message}`,
          });
        });
        child.on('close', (code) => {
          clearTimeout(timer);
          finish({
            code,
            stdout: Buffer.concat(outChunks).toString('utf8'),
            stderr: Buffer.concat(errChunks).toString('utf8'),
          });
        });
      });

      if (result.spawnError) {
        lastDetail = result.spawnError;
        continue;
      }

      const logBlob = `${result.stdout}\n${result.stderr}`;
      if (/429|too many requests|rate.?limit|blocking requests from your IP|IP has been blocked/i.test(logBlob)) {
        rateLimited = true;
      }

      const picked = pickBestSubtitleFile(tmpDir, preferredLangs);
      if (picked) {
        try {
          const raw = fs.readFileSync(picked.file, 'utf8');
          const transcript = parseSubtitleFileToText(raw);
          if (transcript.length >= 20) {
            return {
              ok: true,
              transcript,
              language: picked.language,
              isAutoGenerated: picked.isAuto,
            };
          }
          lastDetail = `yt-dlp file ${path.basename(picked.file)} quá ngắn (${transcript.length})`;
        } catch (e) {
          lastDetail = e instanceof Error ? e.message : String(e);
        }
      } else {
        lastDetail =
          result.stderr.slice(0, 280) ||
          result.stdout.slice(0, 280) ||
          `yt-dlp exit ${result.code} — không có file sub`;
      }
      // If this inv ran (not spawn miss), try next python only if no file at all
      if (!result.spawnError && /not recognized|No module named|can't open file/i.test(lastDetail)) {
        continue;
      }
      // Rate-limit: no point trying every python with same IP
      if (rateLimited) break;
    }

    if (!anySpawned) {
      return {
        ok: false,
        detail:
          'Không chạy được yt-dlp (cài: pip install yt-dlp, hoặc thêm yt-dlp vào PATH).',
      };
    }
    return {
      ok: false,
      detail: lastDetail || 'yt-dlp không lấy được phụ đề.',
      rateLimited,
    };
  } finally {
    // Cleanup temp subs (best-effort)
    if (tmpDir) {
      try {
        fs.rmSync(tmpDir, { recursive: true, force: true });
      } catch {
        /* ignore */
      }
    }
  }
}

async function fetchText(url: string, init?: RequestInit): Promise<string> {
  const res = await fetch(url, {
    ...init,
    headers: {
      'User-Agent':
        'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36',
      'Accept-Language': 'vi-VN,vi;q=0.9,en-US;q=0.8,en;q=0.7',
      ...(init?.headers || {}),
    },
  });
  if (!res.ok) throw new Error(`HTTP ${res.status} fetching ${url.slice(0, 80)}`);
  return res.text();
}

async function fetchOembed(videoId: string): Promise<{ title?: string; author?: string }> {
  try {
    const u = `https://www.youtube.com/oembed?url=${encodeURIComponent(watchUrl(videoId))}&format=json`;
    const res = await fetch(u, {
      headers: { 'User-Agent': 'Mozilla/5.0' },
    });
    if (!res.ok) return {};
    const j = (await res.json()) as { title?: string; author_name?: string };
    return { title: j.title, author: j.author_name };
  } catch {
    return {};
  }
}

function resolvePythonCoreScript(fileName: string): string | null {
  const resourcesPath =
    (process as NodeJS.Process & { resourcesPath?: string }).resourcesPath || '';
  const cwd = process.cwd();
  const candidates = [
    resourcesPath
      ? path.join(resourcesPath, 'app.asar.unpacked', 'src', 'python_core', fileName)
      : '',
    resourcesPath
      ? path.join(resourcesPath, 'src', 'python_core', fileName)
      : '',
    resourcesPath ? path.join(resourcesPath, 'python_core', fileName) : '',
    path.join(cwd, 'src', 'python_core', fileName),
    path.join(cwd, 'python_core', fileName),
  ].filter(Boolean);
  for (const p of candidates) {
    if (fs.existsSync(p)) return p;
  }
  return null;
}

