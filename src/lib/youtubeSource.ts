function watchUrl(videoId: string): string {
  return `https://www.youtube.com/watch?v=${videoId}`;
}

function decodeHtmlEntities(text: string): string {
  return text
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&#x27;/g, "'")
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)))
    .replace(/&#x([0-9a-fA-F]+);/g, (_, h) => String.fromCharCode(parseInt(h, 16)));
}

function truncate(s: string, max: number): string {
  const t = s.trim();
  if (t.length <= max) return t;
  return `${t.slice(0, max - 1).trimEnd()}…`;
}

function parsePlayerResponse(html: string): Record<string, unknown> | null {
  const markers = [
    /ytInitialPlayerResponse\s*=\s*(\{)/,
    /var\s+ytInitialPlayerResponse\s*=\s*(\{)/,
  ];
  for (const re of markers) {
    const m = html.match(re);
    if (!m || m.index == null) continue;
    const start = m.index + m[0].length - 1;
    const json = extractBalancedJson(html, start);
    if (json) {
      try {
        return JSON.parse(json) as Record<string, unknown>;
      } catch {
        /* try next */
      }
    }
  }
  return null;
}

/** Extract JSON object starting at `{` by brace balance (string-aware). */
function extractBalancedJson(src: string, startIdx: number): string | null {
  if (src[startIdx] !== '{') return null;
  let depth = 0;
  let inStr = false;
  let esc = false;
  for (let i = startIdx; i < src.length; i++) {
    const c = src[i];
    if (inStr) {
      if (esc) {
        esc = false;
      } else if (c === '\\') {
        esc = true;
      } else if (c === '"') {
        inStr = false;
      }
      continue;
    }
    if (c === '"') {
      inStr = true;
      continue;
    }
    if (c === '{') depth++;
    else if (c === '}') {
      depth--;
      if (depth === 0) return src.slice(startIdx, i + 1);
    }
  }
  return null;
}

type CaptionTrack = {
  baseUrl: string;
  languageCode?: string;
  name?: string;
  kind?: string;
  vssId?: string;
};

function pickCaptionTrack(
  tracks: CaptionTrack[],
  preferredLangs: string[],
): CaptionTrack | null {
  if (!tracks.length) return null;
  const norm = preferredLangs.map((l) => l.toLowerCase().split('-')[0]);

  const score = (t: CaptionTrack): number => {
    const code = (t.languageCode || '').toLowerCase();
    const base = code.split('-')[0];
    let s = 0;
    const prefIdx = norm.indexOf(base);
    if (prefIdx >= 0) s += 100 - prefIdx * 10;
    // Prefer manual over ASR
    if (t.kind !== 'asr' && !String(t.vssId || '').includes('.a')) s += 20;
    if (base === 'vi') s += 5;
    if (base === 'en') s += 3;
    return s;
  };

  return [...tracks].sort((a, b) => score(b) - score(a))[0] || null;
}

function parseCaptionXml(xml: string): string {
  const parts: string[] = [];
  const re = /<text\b[^>]*>([\s\S]*?)<\/text>/gi;
  let m: RegExpExecArray | null;
  while ((m = re.exec(xml)) !== null) {
    const raw = m[1]
      .replace(/<[^>]+>/g, ' ')
      .replace(/\n+/g, ' ')
      .trim();
    const text = decodeHtmlEntities(raw).replace(/\s+/g, ' ').trim();
    if (text) parts.push(text);
  }
  return parts.join(' ').replace(/\s+/g, ' ').trim();
}

function parseCaptionJson3(jsonText: string): string {
  try {
    const data = JSON.parse(jsonText) as {
      events?: Array<{ segs?: Array<{ utf8?: string }> }>;
    };
    const parts: string[] = [];
    for (const ev of data.events || []) {
      for (const seg of ev.segs || []) {
        const t = (seg.utf8 || '').replace(/\n/g, ' ').trim();
        if (t && t !== '\n') parts.push(t);
      }
    }
    return parts.join(' ').replace(/\s+/g, ' ').trim();
  } catch {
    return '';
  }
}

async function fetchText(url: string, init?: RequestInit): Promise<string> {
  const res = await fetch(url, {
    ...init,
    headers: {
      'User-Agent':
        'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36',
      'Accept-Language': 'vi-VN,vi;q=0.9,en-US;q=0.8,en;q=0.7',
      ...(init?.headers || {}),
    },
  });
  if (!res.ok) throw new Error(`HTTP ${res.status} fetching ${url.slice(0, 80)}`);
  return res.text();
}

async function fetchOembed(videoId: string): Promise<{ title?: string; author?: string }> {
  try {
    const u = `https://www.youtube.com/oembed?url=${encodeURIComponent(watchUrl(videoId))}&format=json`;
    const res = await fetch(u, {
      headers: { 'User-Agent': 'Mozilla/5.0' },
    });
    if (!res.ok) return {};
    const j = (await res.json()) as { title?: string; author_name?: string };
    return { title: j.title, author: j.author_name };
  } catch {
    return {};
  }
}

function resolveTranscriptScript(): string | null {
  const resourcesPath =
    (process as NodeJS.Process & { resourcesPath?: string }).resourcesPath || '';
  const cwd = process.cwd();
  const candidates = [
    // Packaged Electron (extraResources)
    resourcesPath
      ? path.join(resourcesPath, 'app.asar.unpacked', 'src', 'python_core', 'fetch_youtube_transcript.py')
      : '',
    resourcesPath
      ? path.join(resourcesPath, 'src', 'python_core', 'fetch_youtube_transcript.py')
      : '',
    resourcesPath
      ? path.join(resourcesPath, 'python_core', 'fetch_youtube_transcript.py')
      : '',
    path.join(cwd, 'src', 'python_core', 'fetch_youtube_transcript.py'),
    path.join(cwd, 'python_core', 'fetch_youtube_transcript.py'),
  ].filter(Boolean);
  for (const p of candidates) {
    if (fs.existsSync(p)) return p;
  }
  return null;
}

/**
 * Python candidates for youtube-transcript-api.
 * Order: PATH `python`/`py` first (user often `pip install` here), then
 * resolvePythonExe (portable / SuperAudioTools — may lack youtube-transcript-api).
 * Ver 1.0.5 bug: only bare PATH names; then preferred Omni python without package
 * wasted first attempt. Timedtext still runs if all Python fail.
 */
function pythonBins(): string[] {
  const bins: string[] = [];
  if (process.platform === 'win32') {
    bins.push('python', 'py', 'python3');
  } else {
    bins.push('python3', 'python');
  }
  try {
    const preferred = resolvePythonExe();
    // Avoid pushing bare "python" twice; absolute paths always append
    if (preferred && preferred !== 'python' && preferred !== 'py' && preferred !== 'python3') {
      bins.push(preferred);
    }
  } catch {
    /* ignore */
  }
  return [...new Set(bins.map((b) => b.trim()).filter(Boolean))];
}

/**
 * Timedtext / player caption track — same content type as captions (NOT description).
 * Used only after Python path fails so white machines / missing pip package still work.
 */
async function fetchTranscriptViaTimedtext(
  tracks: CaptionTrack[],
  preferredLangs: string[],
): Promise<{
  ok: true;
  transcript: string;
  language?: string;
  isAutoGenerated?: boolean;
} | { ok: false; detail: string }> {
  if (!tracks.length) {
    return { ok: false, detail: 'Player không có captionTracks.' };
  }
  const track = pickCaptionTrack(tracks, preferredLangs);
  if (!track?.baseUrl) {
    return { ok: false, detail: 'Không chọn được caption track phù hợp.' };
  }
  try {
    // Prefer json3 then srv3/xml
    const base = track.baseUrl;
    const urls = [
      base.includes('fmt=') ? base : `${base}${base.includes('?') ? '&' : '?'}fmt=json3`,
      base,
    ];
    let lastDetail = '';
    for (const u of urls) {
      try {
        const res = await fetch(u, {
          headers: {
            'User-Agent':
              'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36',
            Accept: 'application/json, text/xml, */*',
            Referer: 'https://www.youtube.com/',
            'Accept-Language': 'vi-VN,vi;q=0.9,en-US;q=0.8,en;q=0.7',
          },
        });
        const body = await res.text();
        if (res.status === 429 || /Sorry\.\.\.|too many requests|rate.?limit/i.test(body)) {
          return {
            ok: false,
            detail: `Timedtext HTTP ${res.status} (YouTube rate-limit / chặn IP).`,
          };
        }
        if (!res.ok) {
          lastDetail = `Timedtext HTTP ${res.status}`;
          continue;
        }
        let text = '';
        if (body.trimStart().startsWith('{') || body.includes('"events"')) {
          text = parseCaptionJson3(body);
        } else {
          text = parseCaptionXml(body);
        }
        if (text.length >= 20) {
          return {
            ok: true,
            transcript: text,
            language: track.languageCode,
            isAutoGenerated:
              track.kind === 'asr' || String(track.vssId || '').includes('.a'),
          };
        }
        lastDetail = `Track ${track.languageCode || '?'} quá ngắn (${text.length} ký tự).`;
      } catch (e) {
        lastDetail = e instanceof Error ? e.message : String(e);
      }
    }
    return { ok: false, detail: lastDetail || 'timedtext empty' };
  } catch (e) {
    return {
      ok: false,
      detail: e instanceof Error ? e.message : String(e),
    };
  }
}

