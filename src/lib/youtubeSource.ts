/** Short toast line: reason + first fix (không cắt giữa đống kỹ thuật). */
export function summarizeYoutubeErrorForToast(full: string, maxLen = 220): string {
  const text = (full || '').trim();
  if (!text) return 'Không lấy được phụ đề YouTube.';
  const why = text.match(/🔎 Vì sao:\s*(.+)/)?.[1]?.trim();
  const firstFix = text
    .split('\n')
    .map((l) => l.trim())
    .find((l) => l.startsWith('• '));
  const core = [why, firstFix].filter(Boolean).join(' ');
  const out = core || text.replace(/\s+/g, ' ');
  if (out.length <= maxLen) return out;
  return `${out.slice(0, Math.max(0, maxLen - 1))}…`;
}

async function fetchTranscriptViaPython(
  videoId: string,
  preferredLangs: string[],
): Promise<PythonTranscriptResult> {
  const script = resolveTranscriptScript();
  if (!script) {
    return {
      ok: false,
      code: 'SCRIPT_MISSING',
      detail: 'Không tìm thấy fetch_youtube_transcript.py trong project/app pack.',
      triedBins: [],
    };
  }
  const langs = preferredLangs.map((l) => l.split('-')[0]).join(',');
  const triedBins: string[] = [];
  let lastFail: PythonTranscriptFail | null = null;
  let anySpawned = false;

  for (const bin of pythonBins()) {
    triedBins.push(bin);
    try {
      const result = await new Promise<PythonTranscriptResult>((resolve) => {
        let settled = false;
        const finish = (v: PythonTranscriptResult) => {
          if (settled) return;
          settled = true;
          resolve(v);
        };

        let child;
        try {
          child = spawn(bin, [script, videoId, langs], {
            windowsHide: true,
            shell: false,
            env: {
              ...process.env,
              PYTHONIOENCODING: 'utf-8',
              PYTHONUTF8: '1',
            },
          });
          anySpawned = true;
        } catch (e) {
          finish({
            ok: false,
            code: 'PYTHON_NOT_FOUND',
            detail: e instanceof Error ? e.message : String(e),
            triedBins: [...triedBins],
          });
          return;
        }

        const chunks: Buffer[] = [];
        const errChunks: Buffer[] = [];
        const timer = setTimeout(() => {
          try {
            child.kill();
          } catch {
            /* ignore */
          }
          finish({
            ok: false,
            code: 'TIMEOUT',
            detail: `Timeout 60s với binary «${bin}».`,
            triedBins: [...triedBins],
          });
        }, 60_000);

        child.stdout?.on('data', (d: Buffer | string) => {
          chunks.push(Buffer.isBuffer(d) ? d : Buffer.from(String(d)));
        });
        child.stderr?.on('data', (d: Buffer | string) => {
          errChunks.push(Buffer.isBuffer(d) ? d : Buffer.from(String(d)));
        });
        child.on('error', (err) => {
          clearTimeout(timer);
          finish({
            ok: false,
            code: 'PYTHON_NOT_FOUND',
            detail: `${bin}: ${err.message}`,
            triedBins: [...triedBins],
          });
        });
        child.on('close', () => {
          clearTimeout(timer);
          try {
            const out = Buffer.concat(chunks).toString('utf8');
            const line = out.trim().split(/\r?\n/).filter(Boolean).pop() || '';
            if (!line) {
              const stderr = Buffer.concat(errChunks).toString('utf8').trim().slice(0, 200);
              finish({
                ok: false,
                code: 'FETCH_FAILED',
                detail: stderr
                  ? `Python «${bin}» không in JSON. stderr: ${stderr}`
                  : `Python «${bin}» không trả output.`,
                triedBins: [...triedBins],
              });
              return;
            }
            const j = JSON.parse(line) as {
              ok?: boolean;
              transcript?: string;
              language?: string;
              is_auto_generated?: boolean;
              error?: string;
              code?: string;
            };
            if (j.ok && j.transcript && j.transcript.trim().length > 10) {
              finish({
                ok: true,
                transcript: j.transcript.trim(),
                language: j.language,
                isAutoGenerated: j.is_auto_generated,
              });
              return;
            }
            const code =
              normalizePyCode(j.code) ||
              (String(j.error || '').includes('not installed')
                ? 'PACKAGE_MISSING'
                : 'FETCH_FAILED');
            finish({
              ok: false,
              code,
              detail: String(j.error || 'Transcript fetch failed').slice(0, 400),
              triedBins: [...triedBins],
            });
          } catch (e) {
            finish({
              ok: false,
              code: 'FETCH_FAILED',
              detail: e instanceof Error ? e.message : String(e),
              triedBins: [...triedBins],
            });
          }
        });
      });
      if (result.ok) return result;
      lastFail = result;
      // PACKAGE_MISSING / SCRIPT — no point trying other bins for same missing package sometimes still try
      if (result.code === 'PACKAGE_MISSING' || result.code === 'TIMEOUT') {
        // still try next bin in case another python has the package
      }
      if (
        result.code === 'NO_TRANSCRIPT' ||
        result.code === 'TRANSCRIPTS_DISABLED' ||
        result.code === 'VIDEO_UNAVAILABLE' ||
        result.code === 'AGE_RESTRICTED' ||
        result.code === 'EMPTY_TRANSCRIPT'
      ) {
        // video-side failure — other python bins won't help
        return result;
      }
    } catch (e) {
      lastFail = {
        ok: false,
        code: 'FETCH_FAILED',
        detail: e instanceof Error ? e.message : String(e),
        triedBins: [...triedBins],
      };
    }
  }

  if (!anySpawned) {
    return {
      ok: false,
      code: 'PYTHON_NOT_FOUND',
      detail: `Không spawn được Python. Đã thử: ${triedBins.join(', ') || '(trống)'}.`,
      triedBins,
    };
  }

  return (
    lastFail || {
      ok: false,
      code: 'FETCH_FAILED',
      detail: `Không lấy được transcript. Đã thử: ${triedBins.join(', ')}.`,
      triedBins,
    }
  );
}

function buildRewriteBrief(parts: {
  url: string;
  title: string;
  channel: string;
  transcript: string;
  language?: string;
}): string {
  // Chỉ dùng bản chép lời (phụ đề) — không dùng mô tả video
  return [
    '[NGUỒN YOUTUBE — VIẾT LẠI KỊCH BẢN TƯƠNG TỰ]',
    'Nguồn: BẢN CHÉP LỜI / PHỤ ĐỀ video (không dùng description).',
    'Nhiệm vụ: Dựa trên nhịp, ý tưởng, cấu trúc và chủ đề từ chép lời, sáng tạo kịch bản GỐC MỚI (tên nhân vật, chi tiết, twist khác). CẤM copy nguyên văn; chỉ lấy cảm hứng / khung truyện.',
    `URL: ${parts.url}`,
    parts.title ? `Tiêu đề: ${parts.title}` : '',
    parts.channel ? `Kênh: ${parts.channel}` : '',
    parts.language ? `Ngôn ngữ phụ đề: ${parts.language}` : '',
    '',
    '---',
    'BẢN CHÉP LỜI (phụ đề nguồn):',
    parts.transcript,
    '---',
    'Yêu cầu outline: bóc cốt truyện lõi từ chép lời → dàn ý chương → nhân vật (khuyết điểm / động cơ — không ép trope khuyết tật theo thể loại).',
  ]
    .filter((line) => line !== '')
    .join('\n');
}

export async function fetchYoutubeSource(
  urlOrId: string,
  opts?: { preferredLangs?: string[] },
): Promise<YoutubeSourceResult> {
  const videoId = extractYoutubeVideoId(urlOrId);
  if (!videoId) {
    return {
      ok: false,
      errorCode: 'INVALID_URL',
      error: buildYoutubeTranscriptUserError({
        code: 'INVALID_URL',
        detail: String(urlOrId || '').slice(0, 120),
      }),
    };
  }

  const url = watchUrl(videoId);
  const preferredLangs = opts?.preferredLangs?.length
    ? opts.preferredLangs
    : ['vi', 'en', 'en-US', 'en-GB'];

  try {
    let html = '';
    let oembed: { title?: string; author?: string } = {};
    try {
      [html, oembed] = await Promise.all([
        fetchText(url, { headers: { Accept: 'text/html' } }),
        fetchOembed(videoId),
      ]);
    } catch (netErr) {
      // Still try Python captions even if watch page fails
      oembed = await fetchOembed(videoId);
      console.warn(
        '[youtubeSource] watch page fetch failed:',
        netErr instanceof Error ? netErr.message : netErr,
      );
    }

    const player = html ? parsePlayerResponse(html) : null;
    const videoDetails = (player?.videoDetails || {}) as Record<string, unknown>;
    const title =
      (typeof videoDetails.title === 'string' && videoDetails.title) ||
      oembed.title ||
      '';
    const description =
      (typeof videoDetails.shortDescription === 'string' && videoDetails.shortDescription) ||
      '';
    const channel =
      (typeof videoDetails.author === 'string' && videoDetails.author) ||
      oembed.author ||
      '';

    const captionsRoot = player?.captions as Record<string, unknown> | undefined;
    const tracklist = captionsRoot?.playerCaptionsTracklistRenderer as
      | Record<string, unknown>
      | undefined;
    const rawTracks = (tracklist?.captionTracks || []) as Array<Record<string, unknown>>;
    const tracks: CaptionTrack[] = rawTracks
      .map((t) => ({
        baseUrl: String(t.baseUrl || ''),
        languageCode: t.languageCode ? String(t.languageCode) : undefined,
        name:
          t.name && typeof t.name === 'object' && 'simpleText' in (t.name as object)
            ? String((t.name as { simpleText?: string }).simpleText || '')
            : undefined,
        kind: t.kind ? String(t.kind) : undefined,
        vssId: t.vssId ? String(t.vssId) : undefined,
      }))
      .filter((t) => t.baseUrl);

    let transcript = '';
    let language: string | undefined;
    let isAutoGenerated = false;
    let source: YoutubeSourceResult['source'] = 'python_captions';
    let pyFail: PythonTranscriptFail | null = null;
    let timedtextDetail = '';

    // 1) Python youtube-transcript-api (preferred when runtime + package present)
    const py = await fetchTranscriptViaPython(videoId, preferredLangs);
    if (py.ok) {
      if (py.transcript.length >= 20) {
        transcript = py.transcript;
        language = py.language;
        isAutoGenerated = py.isAutoGenerated ?? false;
        source = 'python_captions';
      } else {
        pyFail = {
          ok: false,
          code: 'EMPTY_TRANSCRIPT',
          detail: `Transcript chỉ ${py.transcript.length} ký tự (cần ≥20).`,
          triedBins: [],
        };
      }
    } else {
      pyFail = py;
    }

    // 2) Timedtext / player caption tracks — same content type (captions), NOT description.
    // Fixes ver 1.0.5 white-machine: no system Python / missing youtube-transcript-api.
    if (transcript.length < 20 && tracks.length > 0) {
      const tt = await fetchTranscriptViaTimedtext(tracks, preferredLangs);
      if (tt.ok && tt.transcript.length >= 20) {
        transcript = tt.transcript;
        language = tt.language || language;
        isAutoGenerated = tt.isAutoGenerated ?? isAutoGenerated;
        source = 'captions';
      } else if (!tt.ok) {
        timedtextDetail = tt.detail;
      }
    }

    const transcriptTrim = truncate(transcript, MAX_TRANSCRIPT_CHARS);
    if (!transcriptTrim || transcriptTrim.length < 20) {
      // Prefer actionable classification
      let code: YoutubeTranscriptFailCode = pyFail?.code || 'FETCH_FAILED';
      if (/rate-limit|HTTP 429|chặn IP|IP has been blocked|too many requests/i.test(timedtextDetail)) {
        code = /block/i.test(timedtextDetail) ? 'IP_BLOCKED' : 'RATE_LIMITED';
      }
      if (
        (code === 'FETCH_FAILED' ||
          code === 'NO_TRANSCRIPT' ||
          code === 'PYTHON_NOT_FOUND' ||
          code === 'PACKAGE_MISSING') &&
        tracks.length === 0
      ) {
        code = 'NO_TRANSCRIPT';
      }
      // Tracks exist but py only failed for env reasons → still FETCH after timedtext fail
      if (
        tracks.length > 0 &&
        (code === 'PYTHON_NOT_FOUND' || code === 'PACKAGE_MISSING')
      ) {
        code = 'FETCH_FAILED';
      }
      const detailParts = [
        pyFail?.detail,
        pyFail?.triedBins?.length ? `Python tried: ${pyFail.triedBins.join(', ')}` : '',
        timedtextDetail ? `Timedtext: ${timedtextDetail}` : '',
      ].filter(Boolean);

      return {
        ok: false,
        videoId,
        url,
        title,
        channel,
        description: truncate(description, MAX_DESC_CHARS),
        errorCode: code,
        error: buildYoutubeTranscriptUserError({
          code,
          videoId,
          url,
          title,
          channel,
          detail: detailParts.join(' · '),
          playerCaptionTrackCount: tracks.length,
        }),
      };
    }

    const rewriteBrief = buildRewriteBrief({
      url,
      title,
      channel,
      transcript: transcriptTrim,
      language,
    });

    return {
      ok: true,
      videoId,
      url,
      title,
      description: truncate(description, MAX_DESC_CHARS),
      channel,
      language,
      isAutoGenerated,
      transcript: transcriptTrim,
      wordCount: transcriptTrim.split(/\s+/).filter(Boolean).length,
      source,
      rewriteBrief,
    };
  } catch (e) {
    const msg = e instanceof Error ? e.message : String(e);
    const code: YoutubeTranscriptFailCode =
      /HTTP|fetch|network|ECONN|ENOTFOUND|ETIMEDOUT/i.test(msg) ? 'NETWORK' : 'FETCH_FAILED';
    return {
      ok: false,
      videoId,
      url,
      errorCode: code,
      error: buildYoutubeTranscriptUserError({
        code,
        videoId,
        url,
        detail: msg,
      }),
    };
  }
}
